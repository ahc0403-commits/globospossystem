#!/usr/bin/env python3
"""Generate the pinned Unicode emoji properties used by MISA descriptions."""
import hashlib
import json
from pathlib import Path
import sys

SOURCE = 'https://www.unicode.org/Public/18.0.0/ucd/emoji/emoji-data.txt'
SHA256 = '80d00f8e616a0ef27fd6b8de3b758c06383b5d917e2977709578e68baf733bf1'
ROOT = Path(__file__).resolve().parents[1]

def generate(data):
    assert hashlib.sha256(data).hexdigest() == SHA256, 'Unicode data changed'
    properties = {name: [] for name in ['Emoji', 'Emoji_Presentation', 'Emoji_Component', 'Extended_Pictographic']}
    for raw in data.decode().splitlines():
        line = raw.split('#')[0].strip()
        if not line:
            continue
        code, name = map(str.strip, line.split(';'))
        if name not in properties:
            continue
        bounds = [int(v, 16) for v in code.split('..')]
        properties[name].append((bounds[0], bounds[-1]))
    for name, ranges in properties.items():
        merged = []
        for lo, hi in ranges:
            if merged and lo == merged[-1][1] + 1:
                merged[-1][1] = hi
            else:
                merged.append([lo, hi])
        properties[name] = merged
    document = {'unicode_version': '18.0.0', 'source': SOURCE, 'sha256': SHA256, 'properties': properties}
    (ROOT/'scripts/data/misa_emoji_properties.json').write_text(json.dumps(document, indent=2)+'\n')
    lines = ['// Generated by scripts/generate_misa_emoji_data.py. Do not edit.', '// Unicode 18.0.0; Unicode-3.0 license. See docs/vendor/unicode-LICENSE.txt.', '// Source: '+SOURCE, '// SHA-256: '+SHA256, '']
    for name, ranges in properties.items():
        identifier = 'misa'+''.join(v.title() for v in name.split('_'))+'Ranges'
        lines.append('const '+identifier+' = <(int, int)>[')
        lines.extend(f'  (0x{lo:X}, 0x{hi:X}),' for lo, hi in ranges)
        lines.append('];\n')
    (ROOT/'lib/features/admin/misa_emoji_data.dart').write_text('\n'.join(lines))

if __name__ == '__main__':
    generate(Path(sys.argv[1]).read_bytes())
