#!/usr/bin/env python3
"""Build the atomic production release from the reviewed canonical migrations."""
from pathlib import Path
import argparse
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
COMPONENTS = sorted(
    p.name for p in (ROOT / 'supabase/migrations').glob('*.sql')
    if '20261021163000' <= p.name[:14] <= '20261022193000'
    and p.name[:14] != '20261021230000'
)
OUTPUT = ROOT / 'scripts/releases/20261022200000_store_lifecycle_release.sql'


def build():
    if len(COMPONENTS) != 35:
        raise SystemExit('Release requires the reviewed 35-component dependency set')
    result = '-- GENERATED by scripts/build_store_lifecycle_release.py\n'
    result += '-- production-gate: self-verifying\nBEGIN;\n'
    result += "SET LOCAL lock_timeout='5s';\nSET LOCAL statement_timeout='60s';\n"
    result += 'CREATE TEMP TABLE lifecycle_release_components(version text PRIMARY KEY,name text,sha256 text) ON COMMIT DROP;\n'
    for name in COMPONENTS:
        raw = (ROOT / 'supabase/migrations' / name).read_bytes()
        version, slug = name[:-4].split('_', 1)
        result += "INSERT INTO lifecycle_release_components VALUES ('%s','%s','%s');\n" % (version, slug, hashlib.sha256(raw).hexdigest())
    result += (ROOT / 'scripts/releases/store_lifecycle_release_header.sql').read_text()
    for name in COMPONENTS:
        source = (ROOT / 'supabase/migrations' / name).read_text()
        if len(re.findall(r'(?m)^BEGIN;\s*$', source)) != 1 or len(re.findall(r'(?m)^COMMIT;\s*$', source)) != 1:
            raise SystemExit('Unexpected transaction boundary: ' + name)
        source = re.sub(r'(?m)^BEGIN;\s*$|^COMMIT;\s*$', '', source)
        result += '\n-- COMPONENT ' + name + '\n' + source.rstrip() + '\n'
    result += (ROOT / 'scripts/releases/store_lifecycle_release_footer.sql').read_text()
    result += (ROOT / 'scripts/verify_store_lifecycle_release.sql').read_text()
    result += "NOTIFY pgrst, 'reload schema';\nCOMMIT;\n"
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = build()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Lifecycle release is stale; run scripts/build_store_lifecycle_release.py')
        print('STORE_LIFECYCLE_ATOMIC_RELEASE=PASS components=35 transactions=1')
    else:
        OUTPUT.write_text(content)
